"""Retrieval spot-check: does `semantic_search` put the right trial near the top?

Runs the labelled question set in `evals/retrieval/clinical_gold.json` through
the same hybrid query the MCP tool uses, then reports hit@1/3/5/10 and MRR and
writes `docs/EVAL_RETRIEVAL.md` — including every miss and what came back
instead. Needs the clinical corpus ingested and a VOYAGE_API_KEY (each question
costs one query embedding).

    uv run python scripts/eval_retrieval.py            # score + rewrite the report
    uv run python scripts/eval_retrieval.py --no-write # score only
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from core.config import settings
from core.store.connection import close_pool, init_pool
from core.tools.semantic_search import lexical_only, query_documents

logger = logging.getLogger("scripts.eval_retrieval")

ROOT = Path(__file__).resolve().parent.parent
GOLD_PATH = ROOT / "evals" / "retrieval" / "clinical_gold.json"
REPORT_PATH = ROOT / "docs" / "EVAL_RETRIEVAL.md"
CUTOFFS = (1, 3, 5, 10)
TOP_K = 10


async def run_questions(source_id: str, questions: list[dict[str, str]]) -> list[dict[str, Any]]:
    pool = await init_pool(settings.database_url)
    results: list[dict[str, Any]] = []
    try:
        for q in questions:
            rows = await query_documents(pool, source_id, q["question"], top_k=TOP_K)
            returned = [r["doc_id"] for r in rows]
            rank = returned.index(q["gold"]) + 1 if q["gold"] in returned else None
            results.append(
                {
                    "id": q["id"],
                    "question": q["question"],
                    "gold": q["gold"],
                    "rank": rank,
                    "top1_id": returned[0] if returned else None,
                    "top1_title": rows[0]["title"] if rows else None,
                }
            )
            logger.info("%s rank=%s", q["id"], rank or "miss")
    finally:
        await close_pool()
    return results


def score(results: list[dict[str, Any]]) -> dict[str, float]:
    n = len(results)
    out = {f"hit@{k}": sum(1 for r in results if r["rank"] and r["rank"] <= k) / n for k in CUTOFFS}
    out["mrr"] = sum(1 / r["rank"] for r in results if r["rank"]) / n
    return out


ANALYSIS_MARKER = "<!-- hand-written error analysis below; preserved across re-runs -->"


def render(
    gold: dict[str, Any],
    results: list[dict[str, Any]],
    scores: dict[str, float],
    carryover: str = "",
) -> str:
    n = len(results)
    misses = [r for r in results if r["rank"] is None or r["rank"] > 1]
    lines = [
        "# Retrieval spot-check — clinical corpus",
        "",
        f"_Generated by `scripts/eval_retrieval.py` on "
        f"{datetime.now(UTC).date().isoformat()} against {gold['corpus']} "
        f"({n} labelled questions, top-{TOP_K} retrieved)._",
        "",
        "## Results",
        "",
        "| Metric | Score |",
        "|---|---|",
    ]
    for k in CUTOFFS:
        lines.append(f"| hit@{k} | {scores[f'hit@{k}']:.0%} ({int(scores[f'hit@{k}'] * n)}/{n}) |")
    lines += [
        f"| MRR | {scores['mrr']:.3f} |",
        "",
        "`hit@k` = the labelled trial appears in the top *k*. MRR averages 1/rank "
        "(0 when the trial never appears).",
        "",
        "## Method",
        "",
        f"- {gold['method']}",
        "- Questions run through `query_documents` — the same hybrid "
        "(pgvector cosine + Postgres full-text, fused with Reciprocal Rank Fusion) "
        "query `semantic_search` serves to Claude.",
        "- Scored against the **full** local corpus, not the bundled demo slice.",
        "",
        "## Every question",
        "",
        "| # | Question | Gold trial | Rank |",
        "|---|---|---|---|",
    ]
    for r in results:
        rank = str(r["rank"]) if r["rank"] else "— (not in top 10)"
        lines.append(f"| {r['id']} | {r['question']} | `{r['gold']}` | {rank} |")

    lines += ["", "## Misses and near-misses", ""]
    if not misses:
        lines.append(
            "Every labelled trial ranked first. That is a signal to make the "
            "question set harder, not a victory lap."
        )
    else:
        lines.append(
            "Anything not ranked #1, with what the search returned instead. "
            "A clinically reasonable alternative still counts as a miss here."
        )
        lines.append("")
        for r in misses:
            rank = f"rank {r['rank']}" if r["rank"] else "not in top 10"
            lines.append(
                f"- **{r['id']}** ({rank}) — {r['question']}  \n"
                f"  gold `{r['gold']}`; top hit was `{r['top1_id']}` — {r['top1_title']}"
            )

    lines += [
        "",
        "## What this does not show",
        "",
        "- **The labeller wrote the questions knowing the corpus.** That biases results "
        "upward versus questions written by someone who has never seen it.",
        "- **20 questions is a spot-check, not a benchmark.** Treat the percentages as "
        "indicative; the confidence interval on 20 items is wide.",
        "- **One gold answer per question.** Oncology registries contain many near-duplicate "
        "trials, so a 'miss' is often a defensible alternative rather than a bad result — "
        "read the misses above rather than the headline number.",
        "- **Clinical corpus only.** The openFDA and PubMed corpora are not scored here.",
        "- Re-run with `uv run python scripts/eval_retrieval.py` after any retrieval change; "
        "results move with the corpus and the embedding model.",
        "",
        ANALYSIS_MARKER,
        "",
    ]
    body = "\n".join(lines)
    return body + (carryover.strip() + "\n" if carryover.strip() else "")


async def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-write", action="store_true", help="Score without writing the report.")
    args = parser.parse_args()

    if lexical_only():
        raise SystemExit("VOYAGE_API_KEY is required to score the hybrid retrieval path.")

    gold = json.loads(GOLD_PATH.read_text(encoding="utf-8"))
    results = await run_questions(gold["corpus"], gold["questions"])
    scores = score(results)

    print()
    for k in CUTOFFS:
        print(f"hit@{k}: {scores[f'hit@{k}']:.0%}")
    print(f"MRR:    {scores['mrr']:.3f}")

    if not args.no_write:
        # Regenerate the numbers, keep the interpretation: anything after the
        # marker is hand-written error analysis and survives a re-run.
        carryover = ""
        if REPORT_PATH.exists():
            previous = REPORT_PATH.read_text(encoding="utf-8")
            if ANALYSIS_MARKER in previous:
                carryover = previous.split(ANALYSIS_MARKER, 1)[1]
        REPORT_PATH.write_text(render(gold, results, scores, carryover), encoding="utf-8")
        print(f"\nwrote {REPORT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    asyncio.run(main())
